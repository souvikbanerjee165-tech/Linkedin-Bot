class LinkedInPDFDoc(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(100, 116, 139) # slate-500
        self.cell(0, 8, "LinkedIn B2B Growth & Sales Copilot  |  Executive Content Pack", border=0, align="L", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(148, 163, 184) # slate-400
        self.cell(0, 10, f"Page {self.page_no()} | Confidential B2B Positioning & Content Architecture", border=0, align="C")

class ExportEngine:
    def format_for_linkedin_clipboard(self, raw_text: str) -> str:
        """
        Cleans markdown syntax for direct pasting into the LinkedIn composer.
        Converts markdown headers to plain text with double linebreaks.
        Preserves bullet points and paragraphs cleanly.
        """
        lines = raw_text.split("\n")
        cleaned_lines = []
        for line in lines:
            stripped = line.strip()
            # Strip markdown headers #, ##, ###
            if stripped.startswith("#"):
                clean = stripped.lstrip("#").strip()
                cleaned_lines.append(clean)
            elif stripped.startswith("- ") or stripped.startswith("* "):
                cleaned_lines.append("• " + stripped[2:])
            else:
                cleaned_lines.append(line)
        return "\n".join(cleaned_lines).strip()

    def generate_calendar_csv(self, calendar_items: List[Dict[str, Any]]) -> str:
        """
        Generates CSV format of the content calendar.
        """
        output = io.StringIO()
        fieldnames = [
            "scheduled_date", "day_number", "target_reader", "pillar_name",
            "hook_idea", "core_argument", "evidence_needed", "intended_response",
            "recommended_format", "commercial_intent", "status"
        ]
        writer = csv.DictWriter(output, fieldnames=fieldnames, quoting=csv.QUOTE_MINIMAL)
        writer.writeheader()
        for item in calendar_items:
            row = {k: item.get(k, "") for k in fieldnames}
            writer.writerow(row)
        return output.getvalue()

    def generate_posts_markdown(self, drafts: List[Dict[str, Any]], pack_title: str = "LinkedIn Content Pack") -> str:
        """
        Generates markdown document for single or multiple posts.
        """
        md = [f"# {pack_title}\n"]
        md.append(f"> Generated by LinkedIn B2B Growth Copilot | Local-First Workspace\n")
        
        for i, d in enumerate(drafts, start=1):
            title = d.get("idea_prompt", f"Post #{i}")[:60]
            format_type = d.get("active_draft_format", "standard")
            audience = d.get("target_audience", "B2B Decision Makers")
            score = d.get("buyer_score_total", "N/A")
            content = d.get("final_edited_content") or d.get(f"{format_type}_draft") or d.get("problem_solution_draft") or ""
            claims = d.get("claims_flagged") or []
            visual = d.get("visual_suggestion") or "None specified"

            md.append(f"## Post #{i}: {title}\n")
            md.append(f"- **Format**: `{format_type}`")
            md.append(f"- **Target Audience**: {audience}")
            md.append(f"- **Buyer-Intent Score**: `{score}/100`")
            md.append(f"- **Suggested Visual**: {visual}\n")
            
            if claims:
                md.append("### Factual Claims Needing Verification:")
                for c in claims:
                    md.append(f"- [ ] {c}")
                md.append("")

            md.append("### Publish-Ready Copy:\n")
            md.append("```text")
            md.append(self.format_for_linkedin_clipboard(content))
            md.append("```\n")
            md.append("---\n")

        return "\n".join(md)

    def generate_pdf_pack(self, drafts: List[Dict[str, Any]], title: str = "B2B LinkedIn Weekly Content Pack") -> bytes:
        """
        Generates a clean PDF document using fpdf2.
        """
        pdf = LinkedInPDFDoc(orientation="P", unit="mm", format="A4")
        pdf.set_auto_page_break(auto=True, margin=18)
        pdf.add_page()

        # Cover / Document Title
        pdf.set_font("Helvetica", "B", 18)
        pdf.set_text_color(15, 23, 42) # slate-900
        pdf.cell(0, 10, title, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(71, 85, 105) # slate-600
        pdf.cell(0, 6, "Strategy: Grounded B2B Sales Intelligence, Real Software Architecture & Verified Claims", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(6)

        for i, d in enumerate(drafts, start=1):
            if i > 1:
                pdf.add_page()

            format_type = d.get("active_draft_format", "problem_solution").replace("_", " ").title()
            audience = d.get("target_audience", "B2B Decision Makers")
            score = d.get("buyer_score_total", "N/A")
            content = d.get("final_edited_content") or d.get(f"{d.get('active_draft_format', 'problem_solution')}_draft") or d.get("problem_solution_draft") or ""
            claims = d.get("claims_flagged") or []
            visual = d.get("visual_suggestion") or "None"

            # Post Box Header
            pdf.set_fill_color(241, 245, 249) # slate-100
            pdf.set_font("Helvetica", "B", 12)
            pdf.set_text_color(30, 41, 59)
            pdf.cell(0, 8, f"Post #{i}: {format_type} ({score}/100 Buyer Score)", fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            pdf.ln(2)

            # Metadata tags
            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(79, 70, 229) # indigo-600
            pdf.cell(32, 5, "Target Audience: ", border=0)
            pdf.set_font("Helvetica", "", 9)
            pdf.set_text_color(51, 65, 85)
            pdf.cell(0, 5, str(audience), new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(79, 70, 229)
            pdf.cell(32, 5, "Suggested Visual: ", border=0)
            pdf.set_font("Helvetica", "", 9)
            pdf.set_text_color(51, 65, 85)
            pdf.multi_cell(0, 5, str(visual))
            pdf.ln(3)

            # Verification Warnings
            if claims:
                pdf.set_fill_color(254, 242, 242) # red-50
                pdf.set_font("Helvetica", "B", 8)
                pdf.set_text_color(185, 28, 28) # red-700
                pdf.cell(0, 6, "  CLAIMS REQUIRING VERIFICATION BEFORE PUBLICATION:", fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
                pdf.set_font("Helvetica", "", 8)
                pdf.set_text_color(153, 27, 27)
                for c in claims:
                    clean_c = c.encode('latin-1', 'replace').decode('latin-1')
                    pdf.cell(0, 5, f"   [ ! ] {clean_c}", fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
                pdf.ln(3)

            # Publish Copy Section
            pdf.set_font("Helvetica", "B", 10)
            pdf.set_text_color(15, 23, 42)
            pdf.cell(0, 6, "Publish-Ready Copy:", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            
            # Post Text Body
            pdf.set_font("Helvetica", "", 9.5)
            pdf.set_text_color(30, 41, 59)
            clean_copy = self.format_for_linkedin_clipboard(content)
            safe_text = clean_copy.encode('latin-1', 'replace').decode('latin-1')
            pdf.multi_cell(0, 5.2, safe_text, border=1)
            pdf.ln(4)

        return bytes(pdf.output())

export_engine = ExportEngine()
